#include "event_bus.h"

static QueueHandle_t s_event_queue = NULL;

//--------------------------------------------------------------------------------------------
// API
//--------------------------------------------------------------------------------------------

void event_bus_init(void)
{
    s_event_queue = xQueueCreate(10, sizeof(app_event_t));
}

QueueHandle_t event_bus_get_queue(void)
{
    return s_event_queue;
}
